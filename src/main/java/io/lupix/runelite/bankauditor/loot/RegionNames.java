	private static final Map<Integer, String> BY_REGION = new HashMap<>();

	static
	{
		for (String area : AREAS)
		{
			int bar = area.indexOf('|');
			String name = area.substring(0, bar);
			for (String region : area.substring(bar + 1).split(","))
			{
				BY_REGION.putIfAbsent(Integer.parseInt(region), name);
			}
		}
	}

	private RegionNames()
	{
	}

	/**
	 * @return the area name for a region id, or null when the region has no known name
	 */
	public static String of(int regionId)
	{
		return BY_REGION.get(regionId);
	}
